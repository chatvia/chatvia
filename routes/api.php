<?php

use App\Http\Controllers\Api\V1\Agent\AgentController;
use App\Http\Controllers\Api\V1\Agent\AgentFunctionAttachmentController;
use App\Http\Controllers\Api\V1\Agent\AgentMcpAttachmentController;
use App\Http\Controllers\Api\V1\Agent\AgentSettingsController;
use App\Http\Controllers\Api\V1\Agent\AgentSignInLinkController;
use App\Http\Controllers\Api\V1\Chat\ChatConversationController;
use App\Http\Controllers\Api\V1\Function\FunctionController;
use App\Http\Controllers\Api\V1\Mcp\McpServerController;
use App\Http\Controllers\Api\V1\Source\SourceFileController;
use App\Http\Controllers\Api\V1\Source\SourceListController;
use App\Http\Controllers\Api\V1\Source\SourceTextController;
use App\Http\Controllers\Api\V1\Source\SourceUrlController;
use App\Http\Controllers\Api\V1\Team\RoleController;
use App\Http\Controllers\Api\V1\Team\RoleMemberController;
use App\Http\Controllers\Api\V1\Team\TeamController;
use App\Http\Controllers\Api\V1\Users\ExternalUserController;
use App\Http\Controllers\Webhooks\WebhookChunkController;
use Illuminate\Support\Facades\Route;

Route::post('/chunk', WebhookChunkController::class)->name('webhook.chunk');

/*
|--------------------------------------------------------------------------
| Customer Public API — v1
|--------------------------------------------------------------------------
|
| Authenticated by a single account bearer token. The token owner must own
| the team an agent belongs to; that ownership check lives in
| EnsureCanAccessApiAgent (alias `api.agent`) for every /agents/{agent}/...
| route. Collection routes (listing/creating agents, managing account-level
| MCP servers and functions) operate on the caller's primary team and are
| scoped in their controllers.
|
| OpenAPI documentation is auto-generated by Scramble at /docs/api.
*/
Route::middleware(['auth:sanctum', 'throttle:api'])
    ->prefix('v1')
    ->name('api.v1.')
    ->group(function (): void {

        Route::get('agents', [AgentController::class, 'index'])->name('agents.index');
        Route::post('agents', [AgentController::class, 'store'])->name('agents.store');

        Route::post('users', [ExternalUserController::class, 'store'])->name('users.store');

        Route::get('teams', [TeamController::class, 'index'])->name('teams.index');
        Route::post('teams', [TeamController::class, 'store'])->name('teams.store');
        Route::patch('teams/{team:external_id}', [TeamController::class, 'update'])->name('teams.update');

        // Team roles: grant agents + permissions, then assign users to the role.
        Route::post('teams/{team:external_id}/roles', [RoleController::class, 'store'])->name('teams.roles.store');
        Route::patch('teams/{team:external_id}/roles/{role:external_id}', [RoleController::class, 'update'])->name('teams.roles.update');
        Route::post('teams/{team:external_id}/roles/{role:external_id}/users', [RoleMemberController::class, 'store'])->name('teams.roles.users.store');

        // Account-level MCP servers (CRUD on shared definitions). Attach to
        // specific agents via /agents/{id}/mcps below.
        Route::get('mcps', [McpServerController::class, 'index'])->name('mcps.index');
        Route::get('mcps/{mcp}', [McpServerController::class, 'show'])->name('mcps.show');
        Route::delete('mcps/{mcp}', [McpServerController::class, 'destroy'])->name('mcps.destroy');

        // Account-level functions (CRUD on shared definitions). Attach to
        // specific agents via /agents/{id}/functions below.
        Route::get('functions', [FunctionController::class, 'index'])->name('functions.index');
        Route::post('functions', [FunctionController::class, 'store'])->name('functions.store');
        Route::get('functions/{function}', [FunctionController::class, 'show'])->name('functions.show');
        Route::patch('functions/{function}', [FunctionController::class, 'update'])->name('functions.update');
        Route::delete('functions/{function}', [FunctionController::class, 'destroy'])->name('functions.destroy');

        // Per-agent operations — gated by EnsureCanAccessApiAgent (team ownership).
        Route::middleware('api.agent')->prefix('agents/{agent}')->name('agents.')->group(function (): void {

            Route::get('/', [AgentController::class, 'show'])->name('show');
            Route::patch('/', [AgentController::class, 'update'])->name('update');
            Route::delete('/', [AgentController::class, 'destroy'])->name('destroy');

            // Setup (appearance, widget, embed, leads, persona, model, security, starters, metadata flags)
            Route::patch('settings/{group}', [AgentSettingsController::class, 'update'])->name('settings.update');
            Route::get('settings/{group}', [AgentSettingsController::class, 'show'])->name('settings.show');

            // Knowledge sources
            Route::get('sources', SourceListController::class)->name('sources.index');
            Route::post('sources/files', [SourceFileController::class, 'store'])->name('sources.files.store');
            Route::delete('sources/files/{source}', [SourceFileController::class, 'destroy'])->name('sources.files.destroy');
            Route::post('sources/texts', [SourceTextController::class, 'store'])->name('sources.texts.store');
            Route::delete('sources/texts/{source}', [SourceTextController::class, 'destroy'])->name('sources.texts.destroy');
            Route::post('sources/urls', [SourceUrlController::class, 'store'])->name('sources.urls.store');
            Route::delete('sources/urls/{source}', [SourceUrlController::class, 'destroy'])->name('sources.urls.destroy');

            // Attach / detach account-level MCP servers to this agent. The MCP
            // definitions themselves live at /api/v1/mcps; here we only manage
            // which of them this agent has access to.
            Route::get('mcps', [AgentMcpAttachmentController::class, 'index'])->name('mcps.index');
            Route::post('mcps', [AgentMcpAttachmentController::class, 'store'])->name('mcps.attach');
            Route::delete('mcps/{mcp}', [AgentMcpAttachmentController::class, 'destroy'])->name('mcps.detach');

            // Attach / detach account-level functions to this agent.
            Route::get('functions', [AgentFunctionAttachmentController::class, 'index'])->name('functions.index');
            Route::post('functions', [AgentFunctionAttachmentController::class, 'store'])->name('functions.attach');
            Route::delete('functions/{function}', [AgentFunctionAttachmentController::class, 'destroy'])->name('functions.detach');

            // Mint a one-time sign-in link so one of your end-users can open this
            // agent's chat. The link carries an opaque token consumed on first use.
            Route::post('sign-in-links', [AgentSignInLinkController::class, 'store'])->name('sign-in-links.store');

            // Chat history
            Route::get('conversations', [ChatConversationController::class, 'index'])->name('conversations.index');
            Route::get('conversations/{conversation}', [ChatConversationController::class, 'show'])->name('conversations.show');
            Route::delete('conversations/{conversation}', [ChatConversationController::class, 'destroy'])->name('conversations.destroy');
        });
    });
