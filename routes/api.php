<?php

use App\Http\Controllers\Api\V1\Agents\AgentChatTokenController;
use App\Http\Controllers\Api\V1\Agents\AgentController;
use App\Http\Controllers\Api\V1\Agents\AgentFunctionAttachmentController;
use App\Http\Controllers\Api\V1\Agents\AgentMcpAttachmentController;
use App\Http\Controllers\Api\V1\Agents\AgentSettingsController;
use App\Http\Controllers\Api\V1\Agents\AgentTokenController;
use App\Http\Controllers\Api\V1\Chat\ChatConversationController;
use App\Http\Controllers\Api\V1\Chat\ChatMessageController;
use App\Http\Controllers\Api\V1\Functions\FunctionController;
use App\Http\Controllers\Api\V1\JwtSecretController;
use App\Http\Controllers\Api\V1\Mcps\McpServerController;
use App\Http\Controllers\Api\V1\Sources\SourceFileController;
use App\Http\Controllers\Api\V1\Sources\SourceListController;
use App\Http\Controllers\Api\V1\Sources\SourceTextController;
use App\Http\Controllers\Api\V1\Sources\SourceUrlController;
use App\Http\Controllers\WebhookChunkController;
use Illuminate\Support\Facades\Route;

Route::post('/chunk', WebhookChunkController::class)->name('webhook.chunk');

/*
|--------------------------------------------------------------------------
| Customer Public API — v1
|--------------------------------------------------------------------------
|
| Two token kinds authenticate here:
|
|   • Master token  — tokenable = User. Holds ability `agents:manage`.
|     Used for provisioning: create/list/delete agents, rotate their tokens.
|
|   • Agent token   — tokenable = Agent. Per-agent abilities (chat:send,
|     sources:write, mcps:write, functions:write, agent:write, agent:read).
|     Used for all per-agent operations.
|
| Routes under /agents/{agent}/... resolve the {agent} via external_id and
| are guarded by EnsureCanAccessApiAgent which lets through:
|   - Master tokens whose owning User has team access to the agent.
|   - Agent tokens whose tokenable === the resolved agent.
|
| OpenAPI documentation is auto-generated by Scramble at /docs/api.
*/
Route::middleware(['auth:sanctum', 'throttle:api'])
    ->prefix('v1')
    ->name('api.v1.')
    ->group(function (): void {

        // Provisioning — master token only
        Route::middleware('ability:agents:manage')->group(function (): void {
            Route::get('agents', [AgentController::class, 'index'])->name('agents.index');
            Route::post('agents', [AgentController::class, 'store'])->name('agents.store');
            Route::delete('agents/{agent}', [AgentController::class, 'destroy'])->name('agents.destroy');

            Route::get('agents/{agent}/tokens', [AgentTokenController::class, 'index'])->name('agents.tokens.index');
            Route::post('agents/{agent}/tokens', [AgentTokenController::class, 'store'])->name('agents.tokens.store');
            Route::delete('agents/{agent}/tokens/{tokenId}', [AgentTokenController::class, 'destroy'])->name('agents.tokens.destroy');

            // Account-wide JWT signing secret (shared across all agents)
            Route::get('jwt-secret', [JwtSecretController::class, 'show'])->name('jwt-secret.show');
            Route::post('jwt-secret', [JwtSecretController::class, 'store'])->name('jwt-secret.store');

            // Account-level MCP servers (CRUD on shared definitions). Attach to
            // specific agents via /agents/{id}/mcps below.
            Route::get('mcps', [McpServerController::class, 'index'])->name('mcps.index');
            Route::post('mcps', [McpServerController::class, 'store'])->name('mcps.store');
            Route::get('mcps/{mcp}', [McpServerController::class, 'show'])->name('mcps.show');
            Route::patch('mcps/{mcp}', [McpServerController::class, 'update'])->name('mcps.update');
            Route::delete('mcps/{mcp}', [McpServerController::class, 'destroy'])->name('mcps.destroy');

            // Account-level functions (CRUD on shared definitions). Attach to
            // specific agents via /agents/{id}/functions below.
            Route::get('functions', [FunctionController::class, 'index'])->name('functions.index');
            Route::post('functions', [FunctionController::class, 'store'])->name('functions.store');
            Route::get('functions/{function}', [FunctionController::class, 'show'])->name('functions.show');
            Route::patch('functions/{function}', [FunctionController::class, 'update'])->name('functions.update');
            Route::delete('functions/{function}', [FunctionController::class, 'destroy'])->name('functions.destroy');
        });

        // Per-agent operations — master OR agent token (gated by EnsureCanAccessApiAgent)
        Route::middleware('api.agent')->prefix('agents/{agent}')->name('agents.')->group(function (): void {

            Route::get('/', [AgentController::class, 'show'])->name('show');
            Route::patch('/', [AgentController::class, 'update'])->middleware('ability:agent:write,agents:manage')->name('update');

            // Setup (appearance, widget, embed, leads, persona, model, security, starters, metadata flags)
            Route::patch('settings/{group}', [AgentSettingsController::class, 'update'])->middleware('ability:agent:write,agents:manage')->name('settings.update');
            Route::get('settings/{group}', [AgentSettingsController::class, 'show'])->name('settings.show');

            // Knowledge sources
            Route::get('sources', SourceListController::class)->name('sources.index');
            Route::post('sources/files', [SourceFileController::class, 'store'])->middleware('ability:sources:write,agents:manage')->name('sources.files.store');
            Route::delete('sources/files/{source}', [SourceFileController::class, 'destroy'])->middleware('ability:sources:write,agents:manage')->name('sources.files.destroy');
            Route::post('sources/texts', [SourceTextController::class, 'store'])->middleware('ability:sources:write,agents:manage')->name('sources.texts.store');
            Route::delete('sources/texts/{source}', [SourceTextController::class, 'destroy'])->middleware('ability:sources:write,agents:manage')->name('sources.texts.destroy');
            Route::post('sources/urls', [SourceUrlController::class, 'store'])->middleware('ability:sources:write,agents:manage')->name('sources.urls.store');
            Route::delete('sources/urls/{source}', [SourceUrlController::class, 'destroy'])->middleware('ability:sources:write,agents:manage')->name('sources.urls.destroy');

            // Attach / detach account-level MCP servers to this agent. The MCP
            // definitions themselves live at /api/v1/mcps; here we only manage
            // which of them this agent has access to.
            Route::get('mcps', [AgentMcpAttachmentController::class, 'index'])->name('mcps.index');
            Route::post('mcps', [AgentMcpAttachmentController::class, 'store'])->middleware('ability:mcps:write,agents:manage')->name('mcps.attach');
            Route::delete('mcps/{mcp}', [AgentMcpAttachmentController::class, 'destroy'])->middleware('ability:mcps:write,agents:manage')->name('mcps.detach');

            // Attach / detach account-level functions to this agent.
            Route::get('functions', [AgentFunctionAttachmentController::class, 'index'])->name('functions.index');
            Route::post('functions', [AgentFunctionAttachmentController::class, 'store'])->middleware('ability:functions:write,agents:manage')->name('functions.attach');
            Route::delete('functions/{function}', [AgentFunctionAttachmentController::class, 'destroy'])->middleware('ability:functions:write,agents:manage')->name('functions.detach');

            // Chat
            Route::post('chat-tokens', [AgentChatTokenController::class, 'store'])->middleware('ability:chat:send,agents:manage')->name('chat-tokens.store');
            Route::post('messages', [ChatMessageController::class, 'store'])->middleware('ability:chat:send,agents:manage')->name('messages.store');
            Route::get('conversations', [ChatConversationController::class, 'index'])->name('conversations.index');
            Route::get('conversations/{conversation}', [ChatConversationController::class, 'show'])->name('conversations.show');
            Route::delete('conversations/{conversation}', [ChatConversationController::class, 'destroy'])->middleware('ability:agent:write,agents:manage')->name('conversations.destroy');
        });
    });
