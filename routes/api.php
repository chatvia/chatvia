<?php

declare(strict_types=1);

use App\Http\Controllers\Api\V1\Agent\AgentController;
use App\Http\Controllers\Api\V1\Agent\AgentFunctionAttachmentController;
use App\Http\Controllers\Api\V1\Agent\AgentMcpAttachmentController;
use App\Http\Controllers\Api\V1\Agent\PromptController;
use App\Http\Controllers\Api\V1\Analytics\OverviewAnalyticsController;
use App\Http\Controllers\Api\V1\Analytics\SentimentAnalyticsController;
use App\Http\Controllers\Api\V1\Analytics\SourceUsageAnalyticsController;
use App\Http\Controllers\Api\V1\Analytics\ToneAnalyticsController;
use App\Http\Controllers\Api\V1\Analytics\TopicsAnalyticsController;
use App\Http\Controllers\Api\V1\Audit\AgentAuditLogController;
use App\Http\Controllers\Api\V1\Audit\WorkspaceAuditLogController;
use App\Http\Controllers\Api\V1\Chat\ConversationController;
use App\Http\Controllers\Api\V1\Chat\ConversationMessageController;
use App\Http\Controllers\Api\V1\Chatter\ChatterController;
use App\Http\Controllers\Api\V1\Chatter\ChatterSignInLinkController;
use App\Http\Controllers\Api\V1\Chatter\DeleteChatterController;
use App\Http\Controllers\Api\V1\Chatter\ExternalChatterController;
use App\Http\Controllers\Api\V1\Chatter\GrantChatterAgentsController;
use App\Http\Controllers\Api\V1\Chatter\RevokeChatterAgentsController;
use App\Http\Controllers\Api\V1\Eval\EvalRunController;
use App\Http\Controllers\Api\V1\Form\ExportFormSubmissionsController;
use App\Http\Controllers\Api\V1\Form\FormController;
use App\Http\Controllers\Api\V1\Form\FormSubmissionController;
use App\Http\Controllers\Api\V1\Function\FunctionController;
use App\Http\Controllers\Api\V1\Mcp\McpServerController;
use App\Http\Controllers\Api\V1\Source\SourceFileController;
use App\Http\Controllers\Api\V1\Source\SourceListController;
use App\Http\Controllers\Api\V1\Source\SourceQaController;
use App\Http\Controllers\Api\V1\Source\SourceTextController;
use App\Http\Controllers\Api\V1\Source\SourceUrlController;
use App\Http\Controllers\Api\V1\Team\RoleController;
use App\Http\Controllers\Api\V1\Team\RoleMemberController;
use App\Http\Controllers\Api\V1\Team\TeamController;
use App\Http\Controllers\Api\V1\Team\TeamMemberController;
use App\Http\Controllers\Api\V1\Team\UserController;
use App\Http\Controllers\Api\V1\Topic\TopicController;
use Illuminate\Support\Facades\Route;

/*
|--------------------------------------------------------------------------
| Customer Public API — v1
|--------------------------------------------------------------------------
|
| Authenticated by an account bearer token. The token may belong to the
| workspace owner OR to a teammate the owner has added — so the API enforces
| the SAME permission model as the dashboard:
|
|   • Per-agent routes  → `can.access.agent` (tenant + per-agent access) plus,
|                          for every mutating route, the `agent.permission:*`
|                          the dashboard requires. Owners pass everything.
|   • Account routes     → `team.permission:account.*` (functions, MCP servers,
|                          chatters). Owners and admins bypass.
|   • Owner-only routes  → `api.owner` (create/delete an agent, manage teams) —
|                          operations the dashboard never delegates to teammates.
|
| A teammate without the relevant permission gets 403; a teammate with it acts
| on the owner's workspace exactly as they would in the dashboard.
|
| Records are named by their public id (`external_id`, a UUID; agents have a
| short id of their own). An id that is not a UUID does not match the route,
| so it is a 404 and never reaches the database's uuid columns.
|
| OpenAPI documentation is auto-generated by Scramble at /docs/api.
*/
Route::middleware(['auth:sanctum', 'throttle:api', 'workspace.scope'])
    ->prefix('v1')
    ->name('api.v1.')
    ->whereUuid(['chatter', 'conversation', 'file', 'form', 'function', 'mcp', 'member', 'qa', 'role', 'run', 'team', 'text', 'topic', 'website'])
    ->group(function (): void {

        // Listing agents is scoped per-caller in the controller (owners see
        // every owned agent; teammates see only the agents their role grants).
        // Creating an agent is owner-only, mirroring `AgentPolicy::create`.
        Route::get('agents', [AgentController::class, 'index'])->name('agents.index');
        Route::post('agents', [AgentController::class, 'store'])->middleware('api.owner')->name('agents.store');

        // Managing end-users (chatters) + minting their sign-in links is the
        // API face of the workspace People page — gated by account.chatters.manage.
        Route::middleware('team.permission:account.chatters.manage')->group(function (): void {
            Route::get('chatters', [ChatterController::class, 'index'])->name('chatters.index');
            Route::post('chatters', [ExternalChatterController::class, 'store'])->name('chatters.store');
            // Mint a sign-in link so one of your chatters can open one of your
            // agents' chat. The link's opaque token works until it expires.
            Route::post('chatters/sign', [ChatterSignInLinkController::class, 'store'])->name('chatters.sign');
            Route::get('chatters/{chatter:external_id}', [ChatterController::class, 'show'])->name('chatters.show');
            // Access controls: the monthly message cap and the deactivation switch.
            Route::patch('chatters/{chatter:external_id}', [ChatterController::class, 'update'])->name('chatters.update');
            // Delete a chatter entirely — account, agent grants and chat history.
            Route::delete('chatters/{chatter:external_id}', DeleteChatterController::class)->name('chatters.destroy');
            // Grant / revoke a chatter's access to specific agents (the account is kept).
            Route::post('chatters/{chatter:external_id}/agents', GrantChatterAgentsController::class)->name('chatters.agents.grant');
            Route::delete('chatters/{chatter:external_id}/agents', RevokeChatterAgentsController::class)->name('chatters.agents.revoke');
        });

        // Teams are owner-only (the dashboard blocks teammates from team
        // management via DenyIfTeammate); the team and role Form Requests
        // re-check ownership through TeamPolicy as a second layer. The users
        // list sits here too: it exists to pick a `user_id` for role
        // assignment and sign-in links.
        Route::middleware('api.owner')->group(function (): void {
            Route::get('users', [UserController::class, 'index'])->name('users.index');

            Route::get('teams', [TeamController::class, 'index'])->name('teams.index');
            Route::post('teams', [TeamController::class, 'store'])->name('teams.store');
            Route::get('teams/{team:external_id}', [TeamController::class, 'show'])->name('teams.show');
            Route::patch('teams/{team:external_id}', [TeamController::class, 'update'])->name('teams.update');
            Route::delete('teams/{team:external_id}', [TeamController::class, 'destroy'])->name('teams.destroy');

            // Removing a member detaches them from the team; their account stays.
            Route::delete('teams/{team:external_id}/members/{member:external_id}', [TeamMemberController::class, 'destroy'])->name('teams.members.destroy');

            // Team roles: grant agents + permissions, then assign users to the role.
            Route::post('teams/{team:external_id}/roles', [RoleController::class, 'store'])->name('teams.roles.store');
            Route::patch('teams/{team:external_id}/roles/{role:external_id}', [RoleController::class, 'update'])->name('teams.roles.update');
            Route::delete('teams/{team:external_id}/roles/{role:external_id}', [RoleController::class, 'destroy'])->name('teams.roles.destroy');
            Route::post('teams/{team:external_id}/roles/{role:external_id}/users', [RoleMemberController::class, 'store'])->name('teams.roles.users.store');
        });

        // Account-level MCP servers: list and inspect every connected server
        // (custom + catalog); add and delete custom ones (catalog connectors
        // need the dashboard's OAuth flows). Attach to specific agents via
        // /agents/{id}/mcps below. Gated by account.connectors.
        Route::middleware('team.permission:account.connectors')->group(function (): void {
            Route::get('mcps', [McpServerController::class, 'index'])->name('mcps.index');
            Route::post('mcps', [McpServerController::class, 'store'])->name('mcps.store');
            Route::get('mcps/{mcp}', [McpServerController::class, 'show'])->name('mcps.show');
            Route::delete('mcps/{mcp}', [McpServerController::class, 'destroy'])->name('mcps.destroy');
        });

        // The workspace-wide tool-call audit log (Governed MCP Gateway),
        // read-only — the API face of Settings → Governance, gated by the
        // same account.governance team permission.
        Route::middleware('team.permission:account.governance')->group(function (): void {
            Route::get('audit', WorkspaceAuditLogController::class)->name('audit.index');
        });

        // The prompt library, read-only: how an API client discovers the
        // `prompt_id` the agent endpoints accept. Gated like the dashboard's
        // Library page (404 to hide existence).
        Route::middleware('team.permission:account.prompts,404')->group(function (): void {
            Route::get('prompts', [PromptController::class, 'index'])->name('prompts.index');
        });

        // Account-level functions (CRUD on shared definitions). Attach to
        // specific agents via /agents/{id}/functions below. Gated by account.functions.
        Route::middleware('team.permission:account.functions')->group(function (): void {
            Route::get('functions', [FunctionController::class, 'index'])->name('functions.index');
            Route::post('functions', [FunctionController::class, 'store'])->name('functions.store');
            Route::get('functions/{function}', [FunctionController::class, 'show'])->name('functions.show');
            Route::patch('functions/{function}', [FunctionController::class, 'update'])->name('functions.update');
            Route::delete('functions/{function}', [FunctionController::class, 'destroy'])->name('functions.destroy');
        });

        // Per-agent operations. `can.access.agent` (the same Gate the dashboard
        // uses) enforces tenant isolation + per-agent access; each mutating route
        // then adds the dashboard's agent permission. Reads (show, source list,
        // attachment lists) need access but no extra permission, matching the
        // dashboard's open read pages.
        Route::middleware('can.access.agent')->prefix('agents/{agent}')->name('agents.')->group(function (): void {

            Route::get('/', [AgentController::class, 'show'])->name('show');
            Route::patch('/', [AgentController::class, 'update'])->middleware('agent.permission:agent.setup')->name('update');
            Route::delete('/', [AgentController::class, 'destroy'])->middleware('agent.permission:agent.delete')->name('destroy');

            // Knowledge sources — training is gated per source type; deletion by
            // agent.sources.delete (exactly as routes/agents.php does). A source
            // is looked up by its id through the agent's own sources, so one
            // the agent does not use is a 404.
            Route::get('sources', SourceListController::class)->name('sources.index');
            Route::post('sources/files', [SourceFileController::class, 'store'])->middleware('agent.permission:agent.sources.train.files')->name('sources.files.store');
            Route::delete('sources/files/{file:external_id}', [SourceFileController::class, 'destroy'])->middleware('agent.permission:agent.sources.delete')->name('sources.files.destroy');
            Route::post('sources/texts', [SourceTextController::class, 'store'])->middleware('agent.permission:agent.sources.train.text')->name('sources.texts.store');
            Route::delete('sources/texts/{text:external_id}', [SourceTextController::class, 'destroy'])->middleware('agent.permission:agent.sources.delete')->name('sources.texts.destroy');
            Route::post('sources/urls', [SourceUrlController::class, 'store'])->middleware('agent.permission:agent.sources.train.web')->name('sources.urls.store');
            Route::delete('sources/urls/{website:external_id}', [SourceUrlController::class, 'destroy'])->middleware('agent.permission:agent.sources.delete')->name('sources.urls.destroy');
            Route::post('sources/qas', [SourceQaController::class, 'store'])->middleware('agent.permission:agent.sources.train.qa')->name('sources.qas.store');
            Route::delete('sources/qas/{qa:external_id}', [SourceQaController::class, 'destroy'])->middleware('agent.permission:agent.sources.delete')->name('sources.qas.destroy');

            // Attach / detach account-level MCP servers to this agent. The MCP
            // definitions themselves live at /api/v1/mcps; here we only manage
            // which of them this agent has access to (agent.sources.train.connectors).
            Route::get('mcps', [AgentMcpAttachmentController::class, 'index'])->name('mcps.index');
            Route::post('mcps', [AgentMcpAttachmentController::class, 'store'])->middleware('agent.permission:agent.sources.train.connectors')->name('mcps.attach');
            Route::delete('mcps/{mcp}', [AgentMcpAttachmentController::class, 'destroy'])->middleware('agent.permission:agent.sources.train.connectors')->name('mcps.detach');

            // Attach / detach account-level functions to this agent.
            Route::get('functions', [AgentFunctionAttachmentController::class, 'index'])->name('functions.index');
            Route::post('functions', [AgentFunctionAttachmentController::class, 'store'])->middleware('agent.permission:agent.sources.train.functions')->name('functions.attach');
            Route::delete('functions/{function}', [AgentFunctionAttachmentController::class, 'destroy'])->middleware('agent.permission:agent.sources.train.functions')->name('functions.detach');

            // Chat history — viewing needs agent.chat.view; deletion agent.chat.delete.
            Route::get('conversations', [ConversationController::class, 'index'])->middleware('agent.permission:agent.chat.view')->name('conversations.index');
            Route::get('conversations/{conversation}', [ConversationController::class, 'show'])->middleware('agent.permission:agent.chat.view')->name('conversations.show');
            Route::delete('conversations/{conversation}', [ConversationController::class, 'destroy'])->middleware('agent.permission:agent.chat.delete')->name('conversations.destroy');

            // Chatting with the agent. Like the dashboard's playground, this
            // needs agent access but no extra permission; the message POST has
            // the hosted chat's per-minute cap because each turn costs an LLM
            // call. Replies stream as SSE or fold into one JSON response.
            Route::post('conversations', [ConversationController::class, 'store'])->name('conversations.store');
            Route::get('conversations/{conversation}/messages', [ConversationMessageController::class, 'index'])->middleware('agent.permission:agent.chat.view')->name('conversations.messages.index');
            Route::post('conversations/{conversation}/messages', [ConversationMessageController::class, 'store'])->middleware('throttle:api-chat')->name('conversations.messages.store');

            // Inline forms — reads are open like the dashboard's Forms page;
            // mutations carry its agent.sources.train.connectors permission.
            Route::get('forms', [FormController::class, 'index'])->name('forms.index');
            Route::post('forms', [FormController::class, 'store'])->middleware('agent.permission:agent.sources.train.connectors')->name('forms.store');
            Route::get('forms/{form}', [FormController::class, 'show'])->name('forms.show');
            Route::patch('forms/{form}', [FormController::class, 'update'])->middleware('agent.permission:agent.sources.train.connectors')->name('forms.update');
            Route::delete('forms/{form}', [FormController::class, 'destroy'])->middleware('agent.permission:agent.sources.train.connectors')->name('forms.destroy');

            // Leads: a form's captured submissions, and the CSV export —
            // gated by the dashboard's agent.leads.* permissions. The export
            // and eval runs share the dashboard's throttle prefix, so one
            // person has one budget for both.
            Route::get('forms/{form}/submissions', [FormSubmissionController::class, 'index'])->middleware('agent.permission:agent.leads.view')->name('forms.submissions.index');
            Route::get('forms/{form}/submissions/export', ExportFormSubmissionsController::class)->middleware(['agent.permission:agent.leads.export', 'throttle:10,1,submissions-export'])->name('forms.submissions.export');

            // Eval runs: trigger a suite run and poll it by id (CI use).
            Route::get('evals/runs', [EvalRunController::class, 'index'])->middleware('agent.permission:agent.evals.view')->name('evals.runs.index');
            Route::post('evals/runs', [EvalRunController::class, 'store'])->middleware(['agent.permission:agent.evals.manage', 'throttle:6,1,eval-runs'])->name('evals.runs.store');
            Route::get('evals/runs/{run}', [EvalRunController::class, 'show'])->middleware('agent.permission:agent.evals.view')->name('evals.runs.show');

            // Conversation topics — list, attach/create, rename, detach;
            // gated by agent.topics.manage like the dashboard's Topics page.
            Route::middleware('agent.permission:agent.topics.manage')->group(function (): void {
                Route::get('topics', [TopicController::class, 'index'])->name('topics.index');
                Route::post('topics', [TopicController::class, 'store'])->name('topics.store');
                Route::patch('topics/{topic:external_id}', [TopicController::class, 'update'])->name('topics.update');
                Route::delete('topics/{topic:external_id}', [TopicController::class, 'destroy'])->name('topics.destroy');
            });

            // Read-only analytics — each endpoint carries the same
            // agent.analytics.* permission as its dashboard page.
            Route::get('analytics/overview', OverviewAnalyticsController::class)->middleware('agent.permission:agent.analytics.chats')->name('analytics.overview');
            Route::get('analytics/sentiment', SentimentAnalyticsController::class)->middleware('agent.permission:agent.analytics.sentiment')->name('analytics.sentiment');
            Route::get('analytics/tone', ToneAnalyticsController::class)->middleware('agent.permission:agent.analytics.tone')->name('analytics.tone');
            Route::get('analytics/topics', TopicsAnalyticsController::class)->middleware('agent.permission:agent.analytics.topics')->name('analytics.topics');
            Route::get('analytics/sources', SourceUsageAnalyticsController::class)->middleware('agent.permission:agent.analytics.sources')->name('analytics.sources');

            // The agent's tool-call audit log, read-only (agent.audit.view).
            Route::get('audit', AgentAuditLogController::class)->middleware('agent.permission:agent.audit.view')->name('audit.index');
        });
    });
