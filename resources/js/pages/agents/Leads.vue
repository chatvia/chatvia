<script setup lang="ts">
import { computed, ref } from 'vue';
import { Head, router } from '@inertiajs/vue3';
import AgentLayout from '@/layouts/AgentLayout.vue';
import { Card, CardContent, CardHeader, CardTitle } from '@/components/ui/card';
import { Badge } from '@/components/ui/badge';
import { Button } from '@/components/ui/button';
import { Avatar, AvatarFallback } from '@/components/ui/avatar';
import { ScrollArea, ScrollBar } from '@/components/ui/scroll-area';
import { Separator } from '@/components/ui/separator';
import { 
    Users, 
    Mail, 
    Phone, 
    Building2, 
    Calendar,
    ExternalLink,
    MessageSquare,
    Maximize,
    Minimize
} from 'lucide-vue-next';
import { toast } from 'vue-sonner';

interface Lead {
    id: number;
    name: string | null;
    email: string | null;
    phone: string | null;
    company: string | null;
    message: string | null;
    status: string;
    agent: {
        id: number;
        name: string;
    };
    created_at: string;
    status_color: string;
    status_label: string;
}

interface Agent {
    id: number;
    name: string;
    type: string;
}

interface Props {
    agent: Agent;
    leads: Record<string, Lead[]>;
    statusColumns: Record<string, string>;
}

const props = defineProps<Props>();

const draggedLead = ref<Lead | null>(null);
const dragOverColumn = ref<string | null>(null);
const isFullscreen = ref<boolean>(false);

const statusColors = {
    new: 'bg-blue-500',
    contacted: 'bg-yellow-500', 
    qualified: 'bg-green-500',
    converted: 'bg-purple-500'
};

const getLeadsForStatus = (status: string): Lead[] => {
    return props.leads[status] || [];
};

const getTotalLeads = computed(() => {
    return Object.values(props.leads).flat().length;
});

const getLeadInitials = (lead: Lead): string => {
    if (lead.name) {
        return lead.name
            .split(' ')
            .map(n => n[0])
            .join('')
            .toUpperCase()
            .slice(0, 2);
    }
    if (lead.email) {
        return lead.email[0].toUpperCase();
    }
    return '?';
};

const formatDate = (dateString: string): string => {
    return new Date(dateString).toLocaleDateString('en-US', {
        month: 'short',
        day: 'numeric',
        year: 'numeric'
    });
};

const onDragStart = (event: DragEvent, lead: Lead) => {
    draggedLead.value = lead;
    if (event.dataTransfer) {
        event.dataTransfer.effectAllowed = 'move';
        event.dataTransfer.setData('text/html', '');
    }
};

const onDragEnd = () => {
    draggedLead.value = null;
    dragOverColumn.value = null;
};

const onDragOver = (event: DragEvent, status: string) => {
    event.preventDefault();
    dragOverColumn.value = status;
    if (event.dataTransfer) {
        event.dataTransfer.dropEffect = 'move';
    }
};

const onDragLeave = () => {
    dragOverColumn.value = null;
};

const onDrop = (event: DragEvent, newStatus: string) => {
    event.preventDefault();
    dragOverColumn.value = null;
    
    if (draggedLead.value && draggedLead.value.status !== newStatus) {
        updateLeadStatus(draggedLead.value, newStatus);
    }
    
    draggedLead.value = null;
};

const updateLeadStatus = (lead: Lead, newStatus: string) => {
    router.patch(route('leads.update-status', { lead: lead.id }), {
        status: newStatus
    }, {
        onSuccess: () => {
            toast.success(`Lead moved to ${props.statusColumns[newStatus]}`);
        },
        onError: () => {
            toast.error('Failed to update lead status');
        }
    });
};

const toggleFullscreen = () => {
    isFullscreen.value = !isFullscreen.value;
};
</script>

<template>
    <AgentLayout :agent="agent" title="Leads">
        <Head title="Leads" />
        
        <div class="space-y-6">
            <!-- Header -->
            <div class="flex items-center justify-between">
                <div>
                    <h1 class="text-2xl font-semibold text-foreground">Leads</h1>
                    <p class="text-sm text-muted-foreground">
                        Manage leads generated by {{ agent.name }}
                    </p>
                </div>
                <div class="flex items-center gap-4">
                    <div class="flex items-center gap-2 text-sm text-muted-foreground">
                        <Users class="h-4 w-4" />
                        <span>{{ getTotalLeads }} total leads</span>
                    </div>
                    <div class="flex items-center gap-2">
                        <Button
                            @click="toggleFullscreen"
                            variant="outline"
                            size="sm"
                            class="gap-2"
                        >
                            <component :is="isFullscreen ? Minimize : Maximize" class="h-4 w-4" />
                            {{ isFullscreen ? 'Exit Fullscreen' : 'Fullscreen' }}
                        </Button>
                        <Button 
                            :href="route('leads.index')"
                            as="a"
                            variant="outline"
                            size="sm"
                            class="gap-2"
                        >
                            <ExternalLink class="h-4 w-4" />
                            View All Leads
                        </Button>
                    </div>
                </div>
            </div>

            <!-- Kanban Board Card Container -->
            <Card class="p-0 overflow-hidden"
                :class="[
                    isFullscreen ? 'fixed inset-6 z-50 h-[calc(100vh-3rem)]' : ''
                ]"
            >
                <!-- Fullscreen Header -->
                <div v-if="isFullscreen" class="flex items-center justify-between p-6 border-b">
                    <div>
                        <h2 class="text-xl font-semibold text-foreground">{{ agent.name }} - Leads</h2>
                        <p class="text-sm text-muted-foreground">{{ getTotalLeads }} total leads</p>
                    </div>
                    <Button
                        @click="toggleFullscreen"
                        variant="outline"
                        size="sm"
                        class="gap-2"
                    >
                        <Minimize class="h-4 w-4" />
                        Exit Fullscreen
                    </Button>
                </div>

                <!-- Kanban Columns Container -->
                <ScrollArea 
                    :class="[
                        'w-full whitespace-nowrap',
                        isFullscreen ? 'h-[calc(100vh-15rem)]' : ''
                    ]"
                >
                    <div class="flex w-max space-x-6 p-4">
                        <div 
                            v-for="(label, status) in statusColumns" 
                            :key="status"
                            :class="[
                                'flex flex-col w-80 h-full bg-muted/30 rounded-lg border transition-all duration-200 shrink-0',
                                dragOverColumn === status && draggedLead?.status !== status
                                    ? 'ring-2 ring-primary shadow-lg scale-105'
                                    : ''
                            ]"
                        >
                    <!-- Column Header -->
                    <div class="flex items-center justify-between p-4 border-b bg-card/50 rounded-t-lg">
                        <div class="flex items-center gap-2">
                            <div 
                                :class="[
                                    'w-2 h-2 rounded-full',
                                    status === 'new' ? 'bg-blue-500' :
                                    status === 'contacted' ? 'bg-yellow-500' :
                                    status === 'qualified' ? 'bg-green-500' :
                                    status === 'converted' ? 'bg-purple-500' :
                                    'bg-gray-500'
                                ]"
                            ></div>
                            <h3 class="font-semibold text-sm uppercase tracking-wide text-muted-foreground">{{ label }}</h3>
                        </div>
                        <Badge variant="secondary" class="h-5 px-2 text-xs font-medium">
                            {{ getLeadsForStatus(status).length }}
                        </Badge>
                    </div>

                    <!-- Drop Zone -->
                    <div
                        class="flex-1 p-3 space-y-3 transition-all duration-200"
                        @dragover="onDragOver($event, status)"
                        @dragleave="onDragLeave"
                        @drop="onDrop($event, status)"
                        :class="[
                            dragOverColumn === status && draggedLead?.status !== status
                                ? 'bg-primary/5 border-2 border-dashed border-primary/50 rounded-md'
                                : ''
                        ]"
                    >
                            <!-- Lead Cards -->
                            <Card
                                v-for="lead in getLeadsForStatus(status)"
                                :key="lead.id"
                                draggable="true"
                                @dragstart="onDragStart($event, lead)"
                                @dragend="onDragEnd"
                                :class="[
                                    'cursor-grab active:cursor-grabbing transition-all duration-200 hover:shadow-md group',
                                    draggedLead?.id === lead.id ? 'opacity-60 rotate-2 shadow-lg' : 'hover:scale-[1.02]'
                                ]"
                            >
                                <CardHeader class="pb-3">
                                    <div class="flex items-start gap-3">
                                        <Avatar class="h-8 w-8 flex-shrink-0">
                                            <AvatarFallback 
                                                :class="[
                                                    'text-xs font-medium text-white',
                                                    status === 'new' ? 'bg-blue-500' :
                                                    status === 'contacted' ? 'bg-yellow-500' :
                                                    status === 'qualified' ? 'bg-green-500' :
                                                    status === 'converted' ? 'bg-purple-500' :
                                                    'bg-gray-500'
                                                ]"
                                            >
                                                {{ getLeadInitials(lead) }}
                                            </AvatarFallback>
                                        </Avatar>
                                        <div class="min-w-0 flex-1">
                                            <CardTitle class="text-sm font-medium truncate">
                                                {{ lead.name || 'Anonymous Lead' }}
                                            </CardTitle>
                                            <p class="text-xs text-muted-foreground truncate mt-1">
                                                {{ lead.company || 'No company' }}
                                            </p>
                                        </div>
                                    </div>
                                </CardHeader>
                                
                                <CardContent class="pt-0 space-y-3">
                                    <!-- Contact Info -->
                                    <div class="space-y-2">
                                        <div v-if="lead.email" class="flex items-center gap-2 text-xs">
                                            <Mail class="h-3 w-3 flex-shrink-0 text-muted-foreground" />
                                            <span class="truncate text-muted-foreground">{{ lead.email }}</span>
                                        </div>
                                        <div v-if="lead.phone" class="flex items-center gap-2 text-xs">
                                            <Phone class="h-3 w-3 flex-shrink-0 text-muted-foreground" />
                                            <span class="text-muted-foreground">{{ lead.phone }}</span>
                                        </div>
                                    </div>

                                    <!-- Message Preview -->
                                    <div v-if="lead.message">
                                        <Separator class="my-2" />
                                        <div class="flex items-start gap-2">
                                            <MessageSquare class="h-3 w-3 flex-shrink-0 mt-0.5 text-muted-foreground" />
                                            <p class="text-xs text-muted-foreground line-clamp-2 leading-relaxed">
                                                {{ lead.message }}
                                            </p>
                                        </div>
                                    </div>

                                    <!-- Date -->
                                    <div class="flex items-center justify-center pt-2 text-xs text-muted-foreground">
                                        <div class="flex items-center gap-1">
                                            <Calendar class="h-3 w-3" />
                                            <span>{{ formatDate(lead.created_at) }}</span>
                                        </div>
                                    </div>
                                </CardContent>
                            </Card>

                            <!-- Empty State -->
                            <div 
                                v-if="getLeadsForStatus(status).length === 0"
                                class="flex flex-col items-center justify-center h-96 text-center"
                            >
                                <div 
                                    :class="[
                                        'w-12 h-12 rounded-full mb-3 flex items-center justify-center',
                                        status === 'new' ? 'bg-blue-50 dark:bg-blue-950' :
                                        status === 'contacted' ? 'bg-yellow-50 dark:bg-yellow-950' :
                                        status === 'qualified' ? 'bg-green-50 dark:bg-green-950' :
                                        status === 'converted' ? 'bg-purple-50 dark:bg-purple-950' :
                                        'bg-gray-50 dark:bg-gray-950'
                                    ]"
                                >
                                    <Users 
                                        :class="[
                                            'h-6 w-6',
                                            status === 'new' ? 'text-blue-400' :
                                            status === 'contacted' ? 'text-yellow-400' :
                                            status === 'qualified' ? 'text-green-400' :
                                            status === 'converted' ? 'text-purple-400' :
                                            'text-gray-400'
                                        ]"
                                    />
                                </div>
                                <p class="text-sm text-muted-foreground mb-1">
                                    No {{ label.toLowerCase() }} leads
                                </p>
                                <p class="text-xs text-muted-foreground/60">
                                    Drag leads here to update status
                                </p>
                            </div>
                        </div>
                    </div>
                    </div>
                    <ScrollBar orientation="horizontal" />
                </ScrollArea>
            </Card>
        </div>
    </AgentLayout>
</template>

